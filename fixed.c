static fx Interp(const int32_t *t, uint32_t pos) { // pos: 8.16 step position, 0..256 steps
    uint32_t i = pos >> 16, f = pos & 0xFFFF;
    if (i >= 256) return t[256];
    return t[i] + (fx)(((int64_t)(t[i + 1] - t[i]) * f) >> 16);
}

uint32_t FxTurn(fx radians) { return (uint32_t)(((int64_t)radians * 683565276LL) >> 16); } // 2^32 / (2 pi)

fx FxSinTurn(uint32_t u) {
    uint32_t q = u >> 30, pos = (u >> 6) & 0xFFFFFF;
    if (q & 1) pos = 0x1000000 - pos;
    fx s = Interp(fx_sin_q, pos);
    return q & 2 ? -s : s;
}
fx FxCosTurn(uint32_t u) { return FxSinTurn(u + 0x40000000u); }
fx FxSin(fx radians) { return FxSinTurn(FxTurn(radians)); }
fx FxCos(fx radians) { return FxCosTurn(FxTurn(radians)); }

fx FxAtan2(fx y, fx x) {
    if (!x && !y) return 0;
    int64_t ax = x < 0 ? -(int64_t)x : x, ay = y < 0 ? -(int64_t)y : y;
    fx a = ax >= ay ? Interp(fx_atan_t, (uint32_t)((ay << 24) / ax))
                    : FX_HALF_PI - Interp(fx_atan_t, (uint32_t)((ax << 24) / ay));
    if (x < 0) a = FX_PI - a;
    return y < 0 ? -a : a;
}

static uint32_t ISqrt64(uint64_t n) {
    uint64_t r = 0, bit = 1ULL << 62;
    while (bit > n) bit >>= 2;
    while (bit) {
        if (n >= r + bit) { n -= r + bit; r = (r >> 1) + bit; } else r >>= 1;
        bit >>= 2;
    }
    return (uint32_t)r;
}

fx FxSqrt(fx a) { return a <= 0 ? 0 : (fx)ISqrt64((uint64_t)a << 16); }
fx FxLen(fx x, fx y) { return (fx)ISqrt64((uint64_t)((int64_t)x * x) + (uint64_t)((int64_t)y * y)); }
fx FxLen3(fx x, fx y, fx z) {
    return (fx)ISqrt64((uint64_t)((int64_t)x * x) + (uint64_t)((int64_t)y * y) + (uint64_t)((int64_t)z * z));
}
fx FxMod(fx a, fx m) { return m ? a % m : 0; }

const char *FxStr(fx a, int decimals) {
    static char buf[4][16];
    static int next;
    char *b = buf[next++ & 3];
    static const int scale[4] = { 1, 10, 100, 1000 };
    if (decimals < 0) decimals = 0;
    if (decimals > 3) decimals = 3;
    int neg = a < 0;
    int64_t v = neg ? -(int64_t)a : a;
    v = (v * scale[decimals] + FX_HALF) >> FX_SHIFT;
    int whole = (int)(v / scale[decimals]), part = (int)(v % scale[decimals]);
    if (decimals) snprintf(b, 16, "%s%d.%0*d", neg && v ? "-" : "", whole, decimals, part);
    else snprintf(b, 16, "%s%d", neg && v ? "-" : "", whole);
    return b;
}

fx FxParse(const char *s) {
    while (*s == ' ' || *s == '	') s++;
    int neg = *s == '-';
    if (*s == '-' || *s == '+') s++;
    int64_t whole = 0, frac = 0, scale = 1;
    while (*s >= '0' && *s <= '9' && whole < 32767) whole = whole * 10 + (*s++ - '0');
    if (*s == '.') for (s++; *s >= '0' && *s <= '9'; s++) if (scale < 100000) { frac = frac * 10 + (*s - '0'); scale *= 10; }
    int64_t v = whole * FX_ONE + frac * FX_ONE / scale;
    if (v > INT32_MAX) v = INT32_MAX;
    return (fx)(neg ? -v : v);
}

// Reads an IEEE-754 float stored by an older save, using whole numbers only.
fx FxFromFloatBits(uint32_t b) {
    int exp = (int)((b >> 23) & 0xFF) - 127, neg = (int)(b >> 31);
    if (exp < -16) return 0;
    if (exp > 14) return neg ? -INT32_MAX : INT32_MAX;
    int64_t m = (int64_t)((b & 0x7FFFFF) | 0x800000); // value = m * 2^(exp - 23)
    int sh = exp - 23 + 16;
    int64_t v = sh >= 0 ? m << sh : m >> -sh;
    return (fx)(neg ? -v : v);
}

fx FxTan(fx a) { return FxDiv(FxSin(a), FxCos(a)); }

fx FxExpNeg(fx x) {
    static const fx whole[12] = { 65536, 24109, 8869, 3263, 1200, 442, 162, 60, 22, 8, 3, 1 };
    if (x <= 0) return FX_ONE;
    int n = FxFloor(x);
    if (n >= 12) return 0;
    fx f = FxFrac(x), t = FX_ONE - FxMul(f, FX_ONE - FxMul(f, FX(0.5) - FxMul(f, FX(1.0 / 6) - FxMul(f, FX(1.0 / 24) - FxMul(f, FX(1.0 / 120))))));
    return FxMul(whole[n], t);
}
